export function clampTaskQty(value: number): number {
  if (!Number.isFinite(value) || value < 0) return 0;
  if (value > 1000) return 1000;
  return Math.floor(value);
}

export function stepTaskQty(current: number, delta: number): number {
  return clampTaskQty(current + delta);
}

export function calculateTotalPlanned(
  quantities: Partial<Record<TaskId, number>>,
  enabledTasks?: Partial<Record<TaskId, boolean>>
): number {
  return TASK_IDS.reduce((sum, id) => {
    if (enabledTasks && enabledTasks[id] === false) return sum;
    return sum + clampTaskQty(quantities[id] || 0);
  }, 0);
}

export function calculateAccuracyPercent(correct: number, total: number): number {
  if (total <= 0) return 100;
  return Math.round((correct / total) * 100);
}

export function parseKimAnswerIndices(raw: string, maxDigit = 9): number[] {
  const str = String(raw || '').trim();
  if (!str) return [];

  if (maxDigit <= 9) {
    const regex = new RegExp(`[^1-${maxDigit}]`, 'g');
    return Array.from(
      new Set(
        str
          .replace(regex, '')
          .split('')
          .map(Number)
          .filter((n) => n >= 1 && n <= maxDigit)
      )
    ).sort((a, b) => a - b);
  }

  const rawTokens = str.match(/\d+/g) || [];
  if (rawTokens.length > 1) {
    return Array.from(
      new Set(
        rawTokens
          .map(Number)
          .filter((n) => Number.isFinite(n) && n >= 1 && n <= maxDigit)
      )
    ).sort((a, b) => a - b);
  }

  const s = str.replace(/\D/g, '');
  if (!s) return [];

  // Try strictly increasing partitions 1 <= n_1 < n_2 < ... <= maxDigit (preferring length >= 2)
  const validAscending: number[][] = [];
  const dfs = (idx: number, prev: number, acc: number[]) => {
    if (idx === s.length) {
      validAscending.push(acc.slice());
      return;
    }
    if (s[idx] === '0') return;
    // Try 1-digit if it doesn't strand a following '0'
    if (idx + 1 >= s.length || s[idx + 1] !== '0') {
      const d1 = Number(s[idx]);
      if (d1 > prev && d1 <= maxDigit) {
        acc.push(d1);
        dfs(idx + 1, d1, acc);
        acc.pop();
      }
    }
    // Try 2-digit if it doesn't strand a following '0'
    if (idx + 1 < s.length && (idx + 2 >= s.length || s[idx + 2] !== '0')) {
      const d2 = Number(s.slice(idx, idx + 2));
      if (d2 > prev && d2 >= 10 && d2 <= maxDigit) {
        acc.push(d2);
        dfs(idx + 2, d2, acc);
        acc.pop();
      }
    }
  };
  dfs(0, 0, []);
  if (validAscending.length > 0) {
    const multi = validAscending.filter((p) => p.length >= 2);
    const chosen = multi.length > 0 ? multi[0] : validAscending[0];
    return chosen;
  }

  // Fallback left-to-right scan without stranding '0'
  const out: number[] = [];
  let i = 0;
  while (i < s.length) {
    if (s[i] === '0') {
      i++;
      continue;
    }
    if (i + 1 < s.length && (i + 2 >= s.length || s[i + 2] !== '0')) {
      const two = Number(s.slice(i, i + 2));
      if (two >= 10 && two <= maxDigit) {
        out.push(two);
        i += 2;
        continue;
      }
    }
    const one = Number(s[i]);
    if (one >= 1 && one <= maxDigit) {
      out.push(one);
    }
    i++;
  }
  return Array.from(new Set(out)).sort((a, b) => a - b);
}

export function normalizeKimDigits(raw: string, maxDigit = 5): string {
  if (maxDigit <= 9) {
    const regex = new RegExp(`[^1-${maxDigit}]`, 'g');
    const digits = Array.from(
      new Set(
        String(raw || '')
          .replace(regex, '')
          .split('')
      )
    ).sort();
    return digits.join('');
  }
  return parseKimAnswerIndices(raw, maxDigit).join('');
}

export function normalizeWordAnswer(raw: string): string {
  return String(raw || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^а-яa-z0-9]/gi, '')
    .trim();
}

export function checkFipiQuestionAnswer(
  q: FipiQuestion,
  userRawInput: string | number[]
): {
  isCorrect: boolean;
  pointsEarned: number;
  maxPoints: number;
  correctAnswerDisplay: string;
  userAnswerDisplay: string;
} {
  const maxPoints = TASK_META[q.task]?.maxPoints || (['8', '22'].includes(q.task) ? 2 : 1);
  const kind =
    q.questionKind ||
    (['5', '6', '7'].includes(q.task)
      ? 'word_input'
      : ['8', '22'].includes(q.task)
      ? 'matching_grid'
      : 'rows');

  if (kind === 'word_input') {
    const validAnswers =
      Array.isArray(q.textAnswers) && q.textAnswers.length > 0
        ? q.textAnswers
        : [q.rows.find((r) => r.isCorrectRow)?.letter || ''];
    const normalizedValid = validAnswers.map(normalizeWordAnswer).filter(Boolean);
    const userStr = Array.isArray(userRawInput) ? userRawInput.join('') : String(userRawInput || '');
    const normalizedUser = normalizeWordAnswer(userStr);
    const isCorrect = normalizedUser.length > 0 && normalizedValid.includes(normalizedUser);
    return {
      isCorrect,
      pointsEarned: isCorrect ? maxPoints : 0,
      maxPoints,
      correctAnswerDisplay: (validAnswers[0] || '').toUpperCase(),
      userAnswerDisplay: userStr.trim().toUpperCase() || '—',
    };
  }

  if (kind === 'matching_grid') {
    const targetDigits = q.correctIndices.map(String);
    const targetStr = targetDigits.join('');
    const rawStr = Array.isArray(userRawInput)
      ? userRawInput.map((d) => (d > 0 ? String(d) : '_')).join('')
      : String(userRawInput || '').replace(/\D/g, '');
    let matchCount = 0;
    for (let i = 0; i < targetDigits.length; i++) {
      if (rawStr[i] && rawStr[i] === targetDigits[i]) {
        matchCount++;
      }
    }
    const isCorrect = matchCount === targetDigits.length && rawStr.replace(/\D/g, '').length === targetDigits.length;
    const pointsEarned = isCorrect ? 2 : matchCount >= Math.ceil(targetDigits.length * 0.6) ? 1 : 0;
    return {
      isCorrect,
      pointsEarned,
      maxPoints: 2,
      correctAnswerDisplay: targetStr,
      userAnswerDisplay: rawStr || '—',
    };
  }

  // Standard multi-digit sorted answer (4, 9–21)
  const maxRowDigit = Math.max(9, q.rows?.length || 9, ...(q.correctIndices || [9]));
  const correctIndicesSorted = q.correctIndices.slice().sort((a, b) => a - b);
  const correctStr = correctIndicesSorted.join('');
  const validJoinedSet = new Set<string>([correctStr]);
  if (Array.isArray(q.textAnswers)) {
    for (const alt of q.textAnswers) {
      const altTrim = String(alt || '').trim();
      if (!altTrim) continue;
      const digitsOnly = altTrim.replace(/\D/g, '');
      if (digitsOnly) {
        validJoinedSet.add(digitsOnly);
        if (/^[1-9]+$/.test(digitsOnly) && digitsOnly.length <= 9) {
          validJoinedSet.add(normalizeKimDigits(digitsOnly, 9));
        } else {
          validJoinedSet.add(normalizeKimDigits(digitsOnly, maxRowDigit));
        }
      }
      const tokenNums = (altTrim.match(/\d+/g) || [])
        .map(Number)
        .filter((n) => Number.isFinite(n) && n > 0);
      if (tokenNums.length > 0) {
        const sortedJoined = Array.from(new Set(tokenNums))
          .sort((a, b) => a - b)
          .join('');
        if (sortedJoined) validJoinedSet.add(sortedJoined);
      }
    }
  }

  let userStr = '';
  if (Array.isArray(userRawInput)) {
    userStr = Array.from(
      new Set(userRawInput.filter((n) => Number.isFinite(n) && n > 0))
    )
      .sort((a, b) => a - b)
      .join('');
  } else {
    const rawTrim = String(userRawInput || '').trim();
    const digitsOnly = rawTrim.replace(/\D/g, '');
    const tokenNums = (rawTrim.match(/\d+/g) || [])
      .map(Number)
      .filter((n) => Number.isFinite(n) && n > 0);
    const tokenJoined = Array.from(new Set(tokenNums))
      .sort((a, b) => a - b)
      .join('');
    const kimNorm = normalizeKimDigits(rawTrim, maxRowDigit);
    if (digitsOnly.length > 0 && validJoinedSet.has(digitsOnly)) {
      userStr = digitsOnly;
    } else if (tokenNums.length > 1 && validJoinedSet.has(tokenJoined)) {
      userStr = tokenJoined;
    } else {
      userStr = kimNorm || digitsOnly;
    }
  }

  const isCorrect = userStr.length > 0 && validJoinedSet.has(userStr);
  const displayAltAnswers =
    Array.isArray(q.textAnswers) && q.textAnswers.length > 1
      ? q.textAnswers.join(' или ')
      : correctStr;
  return {
    isCorrect,
    pointsEarned: isCorrect ? 1 : 0,
    maxPoints: 1,
    correctAnswerDisplay: displayAltAnswers,
    userAnswerDisplay: userStr || '—',
  };
}

export function shuffleArray<T>(items: T[]): T[] {
  const arr = items.slice();
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function balanceSprintQuestionsList(questions: SprintQuestion[]): SprintQuestion[] {
  const arr = questions.slice();
  // Prevent >2 identical Task 13 answers (СЛИТНО / РАЗДЕЛЬНО) in a row by swapping ahead
  for (let i = 2; i < arr.length; i++) {
    if (
      arr[i].task === '13' &&
      arr[i - 1].task === '13' &&
      arr[i - 2].task === '13' &&
      arr[i].answer === arr[i - 1].answer &&
      arr[i].answer === arr[i - 2].answer
    ) {
      const swapIdx = arr.findIndex(
        (cand, idx) => idx > i && cand.task === '13' && cand.answer !== arr[i].answer
      );
      if (swapIdx !== -1) {
        [arr[i], arr[swapIdx]] = [arr[swapIdx], arr[i]];
      }
    }
  }

  let lastBtnIdx = -1;
  let streak = 0;

  return arr.map((q) => {
    const isOrthoTask = ['9', '10', '11', '12', '13', '14', '15'].includes(q.task);
    const baseOpts: [string, string] =
      !isOrthoTask && Array.isArray(q.options) && q.options.length >= 2
        ? [q.options[0], q.options[1]]
        : getSmartChoiceOptions(q.task, q.answer, q.prefix, q.suffix);

    if (q.task === '13' || baseOpts[0] === 'СЛИТНО') {
      const btnIdx = q.answer === 'СЛИТНО' ? 0 : 1;
      if (btnIdx === lastBtnIdx) {
        streak++;
      } else {
        lastBtnIdx = btnIdx;
        streak = 1;
      }
      return {
        ...q,
        options: ['СЛИТНО', 'РАЗДЕЛЬНО'] as [string, string],
      };
    }

    const other = baseOpts[0] === q.answer ? baseOpts[1] : baseOpts[0];
    let targetIdx = Math.random() < 0.5 ? 0 : 1;
    if (targetIdx === lastBtnIdx && streak >= 2) {
      targetIdx = targetIdx === 0 ? 1 : 0;
    }
    if (targetIdx === lastBtnIdx) {
      streak++;
    } else {
      lastBtnIdx = targetIdx;
      streak = 1;
    }

    const options: [string, string] =
      targetIdx === 0 ? [q.answer, other] : [other, q.answer];
    return {
      ...q,
      options,
    };
  });
}

