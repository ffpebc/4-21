export function buildWorkoutQueue(
  quantities: Partial<Record<TaskId, number>>,
  mode: WorkoutMode,
  options?: {
    randomize?: boolean;
    shuffleTasks?: boolean;
    enabledTasks?: Partial<Record<TaskId, boolean>>;
  }
): TrainerQuestion[] {
  const bank = getTrainerBank();
  const queue: TrainerQuestion[] = [];
  const randomize = options?.randomize !== false;
  const enabledTasks = options?.enabledTasks;

  const sessionUsedWordStems = new Set<string>();
  const sessionUsedQuestionIds = new Set<string>();

  for (const task of TASK_IDS) {
    if (enabledTasks && enabledTasks[task] === false) continue;
    const count = clampTaskQty(quantities[task] || 0);
    if (count <= 0) continue;

    const rawSprintPool = bank.sprintQuestions.filter((q) => q.task === task);
    const rawFipiPool = bank.fipiQuestions.filter((q) => q.task === task);

    const sprintNeed =
      mode === 'sprint'
        ? count
        : mode === 'fipi'
        ? 0
        : count - Math.floor((count + 1) / 3);
    const fipiNeed = count - sprintNeed;

    // Reset cross-session tracker if fewer than needed unseen items remain
    if (
      randomize &&
      rawSprintPool.length - recentSprintIdsByTask[task].size < sprintNeed
    ) {
      recentSprintIdsByTask[task].clear();
    }
    if (
      randomize &&
      rawFipiPool.length - recentFipiIdsByTask[task].size < fipiNeed
    ) {
      recentFipiIdsByTask[task].clear();
    }

    // 1. Pick non-overlapping FIPI questions first (since 1 FIPI question contains 15 words)
    const pickedFipi: FipiQuestion[] = [];
    if (fipiNeed > 0) {
      const candidates = randomize
        ? [
            ...shuffleArray(rawFipiPool.filter((q) => !recentFipiIdsByTask[task].has(q.id))),
            ...shuffleArray(rawFipiPool.filter((q) => recentFipiIdsByTask[task].has(q.id))),
          ]
        : rawFipiPool;

      // Pass A: Pick tasks whose words have zero overlap with anything used in this session
      for (const fq of candidates) {
        if (pickedFipi.length >= fipiNeed) break;
        if (sessionUsedQuestionIds.has(fq.id)) continue;
        const words = fq.rows.flatMap((r) =>
          r.words.map((w) => `${task}:${w.toLowerCase().replace(/\([^)]*\)/g, '').trim()}`)
        );
        const hasWordOverlap = words.some((w) => sessionUsedWordStems.has(w));
        if (!hasWordOverlap) {
          pickedFipi.push(fq);
          sessionUsedQuestionIds.add(fq.id);
          if (randomize) recentFipiIdsByTask[task].add(fq.id);
          for (const w of words) sessionUsedWordStems.add(w);
        }
      }

      // Pass B: If zero-overlap tasks are exhausted, pick tasks without ID duplicates
      if (pickedFipi.length < fipiNeed) {
        for (const fq of candidates) {
          if (pickedFipi.length >= fipiNeed) break;
          if (!sessionUsedQuestionIds.has(fq.id)) {
            pickedFipi.push(fq);
            sessionUsedQuestionIds.add(fq.id);
            if (randomize) recentFipiIdsByTask[task].add(fq.id);
            for (const r of fq.rows) {
              for (const w of r.words) {
                sessionUsedWordStems.add(`${task}:${w.toLowerCase().replace(/\([^)]*\)/g, '').trim()}`);
              }
            }
          }
        }
      }

      // Pass C: If pool has fewer items than fipiNeed (e.g. cold start with small pool), reuse with unique instanceId
      while (pickedFipi.length < fipiNeed && candidates.length > 0) {
        const recycled = candidates[pickedFipi.length % candidates.length];
        pickedFipi.push({
          ...recycled,
          instanceId: `${recycled.id}-inst-${pickedFipi.length + 1}`,
        });
      }
    }

    // 2. Pick non-overlapping Sprint questions (strictly 0 repeats in session)
    const pickedSprint: SprintQuestion[] = [];
    if (sprintNeed > 0) {
      const candidates = randomize
        ? [
            ...shuffleArray(rawSprintPool.filter((q) => !recentSprintIdsByTask[task].has(q.id))),
            ...shuffleArray(rawSprintPool.filter((q) => recentSprintIdsByTask[task].has(q.id))),
          ]
        : rawSprintPool;

      for (const sq of candidates) {
        if (pickedSprint.length >= sprintNeed) break;
        if (sessionUsedQuestionIds.has(sq.id)) continue;
        const stem = `${sq.task}:${sq.prefix.toLowerCase().trim()}..${sq.suffix.toLowerCase().trim()}:${(sq.context || '').slice(0, 35)}`;
        if (sessionUsedWordStems.has(stem)) continue;
        pickedSprint.push(sq);
        sessionUsedQuestionIds.add(sq.id);
        if (randomize) recentSprintIdsByTask[task].add(sq.id);
        sessionUsedWordStems.add(stem);
      }

      // Fallback only if bank doesn't have enough unseen stems
      if (pickedSprint.length < sprintNeed) {
        for (const sq of candidates) {
          if (pickedSprint.length >= sprintNeed) break;
          if (!sessionUsedQuestionIds.has(sq.id)) {
            pickedSprint.push(sq);
            sessionUsedQuestionIds.add(sq.id);
            if (randomize) recentSprintIdsByTask[task].add(sq.id);
          }
        }
      }
    }

    const balancedSprint = balanceSprintQuestionsList(pickedSprint);

    // 3. Assemble and interleave questions for this task
    let sIdx = 0;
    let fIdx = 0;
    for (let i = 0; i < count; i++) {
      const useFipi = mode === 'fipi' || (mode === 'mixed' && i % 3 === 2);
      if (useFipi && fIdx < pickedFipi.length) {
        const item = pickedFipi[fIdx++];
        queue.push({
          ...item,
          instanceId: `${item.id}-run-${queue.length + 1}-${Math.random().toString(36).slice(2, 7)}`,
        });
      } else if (sIdx < balancedSprint.length) {
        const item = balancedSprint[sIdx++];
        queue.push({
          ...item,
          instanceId: `${item.id}-run-${queue.length + 1}-${Math.random().toString(36).slice(2, 7)}`,
        });
      } else if (fIdx < pickedFipi.length) {
        const item = pickedFipi[fIdx++];
        queue.push({
          ...item,
          instanceId: `${item.id}-run-${queue.length + 1}-${Math.random().toString(36).slice(2, 7)}`,
        });
      } else if (sIdx < balancedSprint.length) {
        const item = balancedSprint[sIdx++];
        queue.push({
          ...item,
          instanceId: `${item.id}-run-${queue.length + 1}-${Math.random().toString(36).slice(2, 7)}`,
        });
      }
    }
  }

  if (randomize && options?.shuffleTasks) {
    return shuffleArray(queue);
  }

  return queue;
}

export function applyAnswerToState(
  state: TrainerState,
  question: TrainerQuestion,
  isCorrect: boolean,
  userChoiceLabel: string,
  isSprintTab = false
): TrainerState {
  const task = question.task;
  const prevTaskStat = state.taskStats[task] || { solved: 0, correct: 0 };
  const updatedTaskStats: Record<TaskId, TaskMasteryStat> = {
    ...state.taskStats,
    [task]: {
      solved: prevTaskStat.solved + 1,
      correct: prevTaskStat.correct + (isCorrect ? 1 : 0),
    },
  };

  let updatedErrorBank = [...state.errorBank];
  if (!isCorrect) {
    const isOrthoSprint = ['9', '10', '11', '12', '13', '14', '15'].includes(question.task);
    const entry: ErrorBankEntry =
      question.kind === 'sprint'
        ? {
            id: `err-${question.id}`,
            task: question.task,
            topic: question.topic,
            wordDisplay: !isOrthoSprint
              ? `${question.prefix} ${question.suffix}`.trim() || question.context.slice(0, 65)
              : question.task === '13'
              ? `${question.prefix} ${question.suffix}`
              : question.task === '14'
              ? `${question.prefix} ${question.suffix}`
              : `${question.prefix}..${question.suffix}`,
            correctWord: !isOrthoSprint
              ? question.answer
              : question.task === '13'
              ? question.answer === 'СЛИТНО'
                ? `${question.prefix.replace(/[()]/g, '')}${question.suffix}`
                : `${question.prefix.replace(/[()]/g, '')} ${question.suffix}`
              : question.task === '14'
              ? formatTask14SolvedWord(question.prefix, question.suffix, question.answer)
              : `${question.prefix}${question.answer.toLowerCase()}${question.suffix}`,
            userChoice: userChoiceLabel,
            correctChoice: question.answer,
            context: question.context,
            explanation: question.explanation,
            rule: question.rule,
            timestamp: Date.now(),
            questionId: question.id,
          }
        : {
            id: `err-${question.id}`,
            task: question.task,
            topic: question.topic,
            wordDisplay: `Задание № ${question.task} · ФИПИ`,
            correctWord: `Задание № ${question.task} (ФИПИ)`,
            userChoice: userChoiceLabel,
            correctChoice:
              question.textAnswers && question.textAnswers.length > 0
                ? question.textAnswers[0].toUpperCase()
                : question.correctIndices.join(''),
            context:
              question.questionKind === 'word_input'
                ? `Правильное слово: ${(question.textAnswers?.[0] || '').toUpperCase()}`
                : question.questionKind === 'matching_grid'
                ? `Соответствие АБВГД: ${question.correctIndices.join('')}`
                : `Подходят варианты: ${question.correctIndices.join(', ')}`,
            explanation: question.rows
              .map((r, idx) =>
                r.isCorrectRow
                  ? `Пункт ${idx + 1} (${r.letter}): ${r.solvedWords.join(', ')}`
                  : null
              )
              .filter(Boolean)
              .join(' | '),
            rule: question.rule,
            timestamp: Date.now(),
            questionId: question.id,
          };

    updatedErrorBank = [
      entry,
      ...updatedErrorBank.filter((e) => e.questionId !== question.id),
    ].slice(0, 120);
  } else {
    updatedErrorBank = updatedErrorBank.filter((e) => e.questionId !== question.id);
  }

  const nextStreak = isSprintTab
    ? isCorrect
      ? state.sprintStreak + 1
      : 0
    : isCorrect
    ? state.sprintStreak + 1
    : 0;
  const nextBestStreak = Math.max(state.bestStreak || 0, nextStreak);

  return {
    ...state,
    totalSolved: state.totalSolved + 1,
    totalCorrect: state.totalCorrect + (isCorrect ? 1 : 0),
    sprintStreak: nextStreak,
    bestStreak: nextBestStreak,
    sprintTotal: isSprintTab ? state.sprintTotal + 1 : state.sprintTotal,
    sprintCorrect: isSprintTab
      ? state.sprintCorrect + (isCorrect ? 1 : 0)
      : state.sprintCorrect,
    taskStats: updatedTaskStats,
    errorBank: updatedErrorBank,
  };
}

export function encodeBackupCode(state: TrainerState): string {
  const compact = {
    v: 28,
    q: TASK_IDS.map((id) => state.quantities[id] || 0),
    en: TASK_IDS.map((id) => (state.enabledTasks?.[id] === false ? 0 : 1)),
    m: state.workoutMode,
    sh: state.isShuffled ? 1 : 0,
    ts: state.totalSolved,
    tc: state.totalCorrect,
    sc: state.sessionsCompleted,
    ss: state.sprintStreak,
    st: state.sprintTotal,
    sr: state.sprintCorrect,
    bs: state.bestStreak || 0,
    bb: state.bestBlitz60 || 0,
    bv: state.bestSurvival || 0,
    ks: TASK_IDS.map((id) => [
      state.taskStats[id]?.solved || 0,
      state.taskStats[id]?.correct || 0,
    ]),
    eb: state.errorBank.slice(0, 40).map((e) => [e.questionId, e.userChoice]),
    sj: (state.sessionJournal || []).slice(0, 15).map((j) => [
      j.title,
      j.total,
      j.correct,
      j.accuracy,
      j.dateLabel,
    ]),
    d: state.darkMode ? 1 : 0,
    p: state.profilePin || '',
  };
  const json = JSON.stringify(compact);
  const utf8Bytes = new TextEncoder().encode(json);
  let binary = '';
  for (let i = 0; i < utf8Bytes.length; i++) {
    binary += String.fromCharCode(utf8Bytes[i]);
  }
  const b64 = btoa(binary)
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
  return `EGE27-${b64}`;
}

export function decodeBackupCode(
  rawCode: string,
  fallbackState: TrainerState = createInitialState()
): TrainerState | null {
  try {
    const trimmed = String(rawCode || '').trim();
    if (!trimmed.startsWith('EGE27-')) return null;
    let b64 = trimmed.slice(6).replace(/-/g, '+').replace(/_/g, '/');
    while (b64.length % 4 !== 0) {
      b64 += '=';
    }
    const binary = atob(b64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
      bytes[i] = binary.charCodeAt(i);
    }
    const json = new TextDecoder().decode(bytes);
    const data = JSON.parse(json);
    if (!data || (data.v !== 27 && data.v !== 28) || !Array.isArray(data.q)) return null;

    const bank = getTrainerBank();
    const quantities: Record<TaskId, number> = { ...fallbackState.quantities };
    const enabledTasks: Record<TaskId, boolean> = { ...fallbackState.enabledTasks };
    const idList: TaskId[] =
      data.v === 27 ? ['9', '10', '11', '12', '13', '14', '15'] : TASK_IDS;

    idList.forEach((id, i) => {
      quantities[id] = clampTaskQty(Number(data.q[i] ?? 5));
      if (Array.isArray(data.en) && data.en[i] !== undefined) {
        enabledTasks[id] = Boolean(data.en[i]);
      }
    });

    const taskStats: Record<TaskId, TaskMasteryStat> = { ...fallbackState.taskStats };
    if (Array.isArray(data.ks)) {
      idList.forEach((id, i) => {
        const pair = data.ks[i];
        if (Array.isArray(pair)) {
          taskStats[id] = {
            solved: Math.max(0, Number(pair[0] || 0)),
            correct: Math.max(0, Number(pair[1] || 0)),
          };
        }
      });
    }

    const restoredErrors: ErrorBankEntry[] = [];
    if (Array.isArray(data.eb)) {
      for (const item of data.eb) {
        if (!Array.isArray(item)) continue;
        const [qId, userChoice] = item;
        const q = bank.byId.get(String(qId));
        if (q && q.kind === 'sprint') {
          const isOrthoSprint = ['9', '10', '11', '12', '13', '14', '15'].includes(q.task);
          restoredErrors.push({
            id: `err-${q.id}`,
            task: q.task,
            topic: q.topic,
            wordDisplay: !isOrthoSprint
              ? `${q.prefix} ${q.suffix}`.trim() || q.context.slice(0, 65)
              : q.task === '13'
              ? `${q.prefix} ${q.suffix}`
              : q.task === '14'
              ? `${q.prefix} ${q.suffix}`
              : `${q.prefix}..${q.suffix}`,
            correctWord: !isOrthoSprint
              ? q.answer
              : q.task === '13'
              ? q.answer === 'СЛИТНО'
                ? `${questionPrefixClean(q.prefix)}${q.suffix}`
                : `${questionPrefixClean(q.prefix)} ${q.suffix}`
              : q.task === '14'
              ? formatTask14SolvedWord(q.prefix, q.suffix, q.answer)
              : `${q.prefix}${q.answer.toLowerCase()}${q.suffix}`,
            userChoice: String(userChoice || '?'),
            correctChoice: q.answer,
            context: q.context,
            explanation: q.explanation,
            rule: q.rule,
            timestamp: Date.now(),
            questionId: q.id,
          });
        } else if (q && q.kind === 'fipi') {
          restoredErrors.push({
            id: `err-${q.id}`,
            task: q.task,
            topic: q.topic,
            wordDisplay: `Задание № ${q.task} · ФИПИ`,
            correctWord: `Задание № ${q.task} (ФИПИ)`,
            userChoice: String(userChoice || '?'),
            correctChoice: q.correctIndices.join(''),
            context: `Подходят строки: ${q.correctIndices.join(', ')}`,
            explanation: q.rows
              .map((r, idx) =>
                r.isCorrectRow
                  ? `Строка ${idx + 1} (${r.letter}): ${r.solvedWords.join(', ')}`
                  : null
              )
              .filter(Boolean)
              .join(' | '),
            rule: q.rule,
            timestamp: Date.now(),
            questionId: q.id,
          });
        }
      }
    }

    const restoredJournal: SessionJournalEntry[] = [];
    if (Array.isArray(data.sj)) {
      data.sj.forEach((arr: unknown, idx: number) => {
        if (Array.isArray(arr)) {
          restoredJournal.push({
            id: `sj-${idx}-${Date.now()}`,
            title: String(arr[0] || 'Занятие'),
            total: Number(arr[1] || 0),
            correct: Number(arr[2] || 0),
            accuracy: Number(arr[3] || 100),
            dateLabel: String(arr[4] || 'Сегодня'),
          });
        }
      });
    }

    return {
      ...fallbackState,
      quantities,
      enabledTasks,
      workoutMode: 'fipi',
      isShuffled: data.sh === undefined ? true : Boolean(data.sh),
      totalSolved: Math.max(0, Number(data.ts || 0)),
      totalCorrect: Math.max(0, Number(data.tc || 0)),
      sessionsCompleted: Math.max(0, Number(data.sc || 0)),
      sprintStreak: Math.max(0, Number(data.ss || 0)),
      sprintTotal: Math.max(0, Number(data.st || 0)),
      sprintCorrect: Math.max(0, Number(data.sr || 0)),
      bestStreak: Math.max(0, Number(data.bs || 0)),
      bestBlitz60: Math.max(0, Number(data.bb || 0)),
      bestSurvival: Math.max(0, Number(data.bv || 0)),
      taskStats,
      errorBank: restoredErrors,
      sessionJournal: restoredJournal,
      darkMode: Boolean(data.d),
      profilePin: typeof data.p === 'string' ? data.p : '',
    };
  } catch {
    return null;
  }
}

export function formatTask14SolvedWord(
  prefix: string,
  suffix: string,
  answer: string
): string {
  const parenMatch = prefix.match(/^(.*)\(([^)]+)\)\s*$/);
  if (parenMatch) {
    const lead = parenMatch[1];
    const parenWord = parenMatch[2].trim();
    const connector =
      answer === 'СЛИТНО' ? '' : answer === 'ДЕФИСНО' ? '-' : ' ';
    return `${lead}${parenWord}${connector}${suffix}`.trim();
  }
  const cleanPref = prefix.replace(/[()]/g, '').trim();
  const connector =
    answer === 'СЛИТНО' ? '' : answer === 'ДЕФИСНО' ? '-' : ' ';
  return `${cleanPref}${connector}${suffix}`.trim();
}

