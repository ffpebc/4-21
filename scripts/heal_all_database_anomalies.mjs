function cleanEntities(str) {
  if (typeof str !== 'string') return str;
  return str
    .replace(/&shy;/g, '')
    .replace(/&ldquo;/g, '«')
    .replace(/&rdquo;/g, '»')
    .replace(/&yacute;/g, 'у');
}

function deepCleanEntities(obj) {
  if (!obj || typeof obj !== 'object') return obj;
  if (Array.isArray(obj)) {
    return obj.map(deepCleanEntities);
  }
  const res = {};
  for (const [k, v] of Object.entries(obj)) {
    if (typeof v === 'string') {
      res[k] = cleanEntities(v);
    } else if (typeof v === 'object' && v !== null) {
      res[k] = deepCleanEntities(v);
    } else {
      res[k] = v;
    }
  }
  return res;
}

