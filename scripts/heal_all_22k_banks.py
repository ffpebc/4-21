        wid = "w-" + sid[len("sp-") :] if sid.startswith("sp-") else sid
        wo = words_by_id.get(wid)
        if task == "14":
            raw_token = f"{s.get('prefix', '')}{s.get('suffix', '')}"
            ctx = s.get("context", "")
            w_res, let_res, rule_res, topic_res, _ = resolve_t14_token(raw_token, ctx)
            s["answer"] = let_res
            s["options"] = ["СЛИТНО", "ДЕФИСНО", "РАЗДЕЛЬНО"]
