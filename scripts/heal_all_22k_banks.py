                s["answer"] = wo["missingLetter"]
                s["context"] = wo.get("context", "")
                s["explanation"] = wo["rule"]
                s["rule"] = wo["rule"]
                if wid in ("w-13-neofamily-13-78314-r3-w1", "w-13-neofamily-13-36948-r1-w1"):
                    s["suffix"] = wo["suffix"]
