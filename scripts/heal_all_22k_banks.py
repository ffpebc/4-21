def extract_single_word_explanation(row_expl: str, word: str, context: str, task: str, missing_letter: str) -> str:
    """
    Given a potentially multi-word FIPI row explanation (where 2 or 3 words are joined by '; '),
    extracts ONLY the segment corresponding to `word` and repairs any inaccuracies in it.
    """
    row_expl = clean_abbreviations(row_expl)
    w_clean = word.strip()

    # Check if we can split row_expl by boundaries where a new word explanation begins:
    # e.g. "; word2 — " or "; «word2» — "
    # Let's find all clauses of the form "<word_header> — <body_text>"
    parts = re.split(r";\s*(?=(?:«?[А-ЯЁа-яёA-Za-z().,\s-]+»?\s*—\s*))", row_expl)
    if len(parts) > 1:
        w_norm = re.sub(r"[^а-яё]", "", w_clean.lower())
        for p in parts:
            header = p.split("—", 1)[0]
            h_norm = re.sub(r"[^а-яё]", "", header.lower())
            if w_norm and (h_norm.startswith(w_norm) or w_norm in h_norm):
                res = p.strip()
                if not res.endswith("."):
                    res += "."
                return fix_single_word_clause(task, w_clean, context, missing_letter, res)

    res = row_expl.strip()
    if not res.endswith("."):
        res += "."
    return fix_single_word_clause(task, w_clean, context, missing_letter, res)


def clean_t13_rule(word: str, ans: str, rule: str, word_id: str) -> str:
    """Cleans Task 13 explanation text, removing multi-row leaks and false participle suffixes."""
    if word_id in T13_EXPLICIT_FIXES:
        return T13_EXPLICIT_FIXES[word_id][2]
    if word_id in T13_MULTIROW_RULE_FIXES:
        return T13_MULTIROW_RULE_FIXES[word_id]
    if word in WORD_EXPLANATIONS:
        return WORD_EXPLANATIONS[word]

    rule = clean_abbreviations(rule)

    # Remove false participle suffix appended to adjectives/nouns/adverbs
    if any(k in rule.lower() for k in ("прилаг", "нареч", "существительн", "местоим", "предлог", "союз", "глагол")):
        rule = re.sub(
            r";\s*у причастия в данном предложении нет зависимых \(пояснительных\) слов и нет противопоставления с союзом «А»",
            "",
            rule,
        )
        rule = re.sub(
            r";\s*при наличии зависимых слов \(или противопоставления с союзом «А»\) частица НЕ с полным причастием пишется раздельно",
            "",
            rule,
        )

    # Fix НЕИЗЪЯСНИМАЯ / НЕСМОЛКАЕМЫЙ called "полное причастие" when they don't exist without НЕ
    if word == "НЕИЗЪЯСНИМАЯ":
        return "«НЕИЗЪЯСНИМАЯ» — прилагательное на -ИМЫЙ, которое не употребляется без НЕ; пишется слитно; поэтому пишется СЛИТНО — «НЕИЗЪЯСНИМАЯ»."
    if word == "НЕСМОЛКАЕМЫЙ":
        return "«НЕСМОЛКАЕМЫЙ» — отглагольное прилагательное на -ЕМЫЙ без зависимых слов в творительном падеже и без противопоставления; с НЕ пишется слитно; поэтому пишется СЛИТНО — «НЕСМОЛКАЕМЫЙ»."
    if word == "НЕМЫСЛИМА":
        return "«НЕМЫСЛИМА» — краткое прилагательное (от «немыслимый», не употребляющегося без НЕ в данном значении); пишется слитно; поэтому пишется СЛИТНО — «НЕМЫСЛИМА»."

    # Replace full-sentence quote at the end `поэтому пишется СЛИТНО/РАЗДЕЛЬНО — «<long sentence>»` with `«<word>»`
    rule = re.sub(
        r"(поэтому (?:с приставкой НЕ-\s+)?пишется (?:СЛИТНО|РАЗДЕЛЬНО)\s*—\s*)«[^»]{25,}»\.?",
        rf"\1«{word}».",
        rule,
    )
    if not rule.endswith("."):
        rule += "."
    return rule


def get_proper_sprint_options(task: str, word: str, ans: str, current_opts: list, rule: str) -> list:
    """Ensures sprint options are orthographically appropriate distractors for the tested morpheme."""
    ans_u = ans.upper()
    w_low = word.lower()
    if task == "10":
        # ПРИ-/ПРЕ- or ПРЕД- or НИЗ-/НИС- with E/I
        if ans_u in ("Е", "И") and (
            w_low.startswith(("при", "пре", "непри", "непре", "беспри", "беспре", "сопри", "вопри", "низ", "нис"))
            or "ПРЕ-/ПРИ-" in rule
            or "ПРЕД-" in rule
            or "НИЗ-/НИС-" in rule
        ):
            return ["Е", "И"]
    elif task == "11":
        if ans_u in ("Е", "И"):
            if (
                re.search(r"(?:ев|ив|чив|лив|ист)(?:ый|ая|ое|ые|ого|ому|ым|ом|ой|ую|ых|ыми|о|е|и)?$", w_low)
                or re.search(r"еват(?:ь|ься)?$|евая$|еваю", w_low)
                or re.search(r"ет[аыуеой]$|еств[оауе]$|енк[аиуеой]$|ечк[аиуеой]$|ец$", w_low)
                or "-ИВ-/-ЕВ-" in rule
                or "-ЧИВ-" in rule
                or "-ЛИВ-" in rule
                or "-ИСТ-" in rule
                or "-ЕТ-" in rule
            ):
                return ["Е", "И"]
    return current_opts


