function classifyAndExplainTask15Word(wordWithNN, answer = 'НН') {
  const clean = wordWithNN.trim();
  const lower = clean.toLowerCase().replace(/ё/g, 'е');

  if (answer === 'Н') {
    if (
      /(?:ены|ена|ено|ен|аны|ана|ано|ан|яны|яна|яно|ян|ты|та|то|т)$/.test(lower) &&
      !/(?:юный|синий|румяный|пряный|зеленый|свиной|багряный|вороной|фазаний|павлиний)/.test(lower)
    ) {
      return {
        topic: 'Краткие страдательные причастия (одна буква Н)',
        rule: 'В кратких страдательных причастиях ВСЕГДА пишется одна буква Н (задача решена, поле вспахано, книга прочитана, удостоены награды).',
        explanation: `«${clean}» — краткое страдательное причастие прошедшего времени; в кратких причастиях всегда пишется одна буква Н.`
      };
    }
    if (/(?:юность|гостиная|гостиница|пряность|труженик|масленица|песчаник|конопляник)/.test(lower)) {
      return {
        topic: 'Существительные с одной буквой Н',
        rule: 'В существительных пишется одна буква Н, если они образованы от основы с одной буквой Н.',
        explanation: `«${clean}» — существительное, образовано от основы с одной буквой Н; пишется одна буква Н.`
      };
    }
    if (/(?:юный|синий|румяный|пряный|зеленый|свиной|багряный|вороной|фазаний|павлиний|бараний|тюлений)/.test(lower)) {
      return {
        topic: 'Непроизводные и притяжательные прилагательные (одна буква Н)',
        rule: 'В непроизводных прилагательных и притяжательных с суффиксом -ИЙ буква Н входит в корень/основу, суффикса -Н- нет.',
        explanation: `«${clean}» — непроизводное/притяжательное прилагательное, буква Н входит в корень/основу; пишется одна буква Н.`
      };
    }
    if (/(?:песчаный|кожаный|глиняный|серебряный|водяной|ледяной|утиный|гусиный|орлиный|куриный|пчелиный|змеиный|соколиный)/.test(lower)) {
      return {
        topic: 'Суффиксы -АН-, -ЯН-, -ИН- в прилагательных (одна буква Н)',
        rule: 'В отымённых прилагательных с суффиксами -АН-, -ЯН-, -ИН- пишется одна буква Н.',
        explanation: `«${clean}» — отымённое прилагательное с суффиксом -АН-/-ЯН-/-ИН-; пишется одна буква Н.`
      };
    }
    return {
      topic: 'Отглагольные прилагательные несовершенного вида (одна буква Н)',
      rule: 'В отглагольных прилагательных несовершенного вида без приставок и зависимых слов пишется одна буква Н.',
      explanation: `«${clean}» — отглагольное прилагательное несовершенного вида без приставки и зависимых слов; пишется одна буква Н.`
    };
  }

  // answer === 'НН'
  if (/(?:стеклянн|оловянн|деревянн)/.test(lower)) {
    return {
      topic: 'Исключения: стеклянный, оловянный, деревянный (две буквы НН)',
      rule: 'Прилагательные стеклянный, оловянный, деревянный являются исключениями и пишутся с двумя буквами НН.',
      explanation: `«${clean}» — слово является исключением; пишется две буквы НН.`
    };
  }
  if (/(?:ник|ниц|ност|ени)[а-яё]*$/.test(lower)) {
    return {
      topic: 'Существительные с двумя буквами НН',
      rule: 'В существительных пишется НН, если они образованы от основы на -Н- с помощью суффикса на -Н- либо от прилагательного/причастия с НН.',
      explanation: `«${clean}» — существительное, образованное от основы на -Н- либо от слова с -НН-; пишется две буквы НН.`
    };
  }
  if (/(?:нно|нне)$/i.test(lower) && !/(?:ого|его|ому|ему|ое|ее)$/i.test(lower) && !/(?:енное|анное|янное|ованное|евное)$/i.test(lower)) {
    return {
      topic: 'Наречия на -О/-Е (две буквы НН)',
      rule: 'В наречиях на -О/-Е пишется столько же букв Н, сколько в прилагательном или причастии, от которого оно образовано.',
      explanation: `«${clean}» — наречие на -О (-Е), образовано от слова с двумя буквами НН; пишется две буквы НН.`
    };
  }
  if (
    /^(?:утр|солом|времен|таинств|девств|современ|государств|торжеств|величеств|экскурсион|традицион|станцион|инфекцион|авиацион|порцион|клятвен|мыслен|бедствен|числен|свойствен|мужествен|единствен|бесформен)/.test(lower) ||
    lower.includes('утрен') || lower.includes('соломен') || lower.includes('времен') || lower.includes('таинствен') || lower.includes('девствен') || lower.includes('современ')
  ) {
    return {
      topic: 'Суффиксы -ЕНН-, -ОНН- в прилагательных (две буквы НН)',
      rule: 'В отымённых прилагательных с суффиксами -ЕНН- и -ОНН- пишется две буквы НН.',
      explanation: `«${clean}» — отымённое прилагательное с суффиксом -ЕНН- (-ОНН-); пишется две буквы НН.`
    };
  }
  if (
    /^(?:туман|осен|весен|камен|истин|старин|сон|длин|картин|былин|кон|лун|машин|окон|пустын|равнин|ран|струн|целин|чугун|закон|кухон|карман|бан|диван|телефон|дюн|степн|глубин|диковин|овчин|былин|сафьян|картон|казен|эндокрин|иммун|подлин|смежн)/.test(lower) ||
    lower.includes('пустын') || lower.includes('туман') || lower.includes('старин') || lower.includes('истин') || lower.includes('длинн') || lower.includes('осенн') || lower.includes('весенн') || lower.includes('каменн') || lower.includes('сафьян') || lower.includes('подлинн') || lower.includes('картонн')
  ) {
    return {
      topic: 'Стык основы на -Н- и суффикса -Н- (две буквы НН)',
      rule: 'На стыке основы (корня) на -Н- и суффикса -Н- всегда пишется две буквы НН.',
      explanation: `«${clean}» — прилагательное, образованное на стыке производящей основы на -Н и суффикса -Н-; пишется две буквы НН.`
    };
  }
  return {
    topic: 'Причастия и отглагольные прилагательные (две буквы НН)',
    rule: 'Две буквы НН пишутся в причастиях и отглагольных словах при наличии хотя бы одного условия: 1) есть приставка кроме НЕ-; 2) есть зависимые слова; 3) суффиксы -ОВА-/-ЕВА-; 4) образовано от глагола совершенного вида.',
    explanation: `«${clean}» — полное страдательное причастие прошедшего времени (образовано от глагола сов. вида / с приставкой / с зависимым словом); пишется две буквы НН.`
  };
}

