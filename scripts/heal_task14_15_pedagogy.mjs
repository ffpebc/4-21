function formatTask14CleanWord(prefix, suffix, answer) {
  const p = (prefix || '').replace(/[()]/g, '').trim();
  const s = (suffix || '').replace(/[()]/g, '').trim();

  if (answer === 'РАЗДЕЛЬНО') {
    return `${p} ${s}`.replace(/\s+/g, ' ').trim().toUpperCase();
  }
  if (answer === 'ДЕФИСНО') {
    return `${p}-${s}`.replace(/\s+/g, '').trim().toUpperCase();
  }
  return `${p}${s}`.replace(/\s+/g, '').trim().toUpperCase();
}

function getTask14Explanation(cleanWord, answer) {
  const w = cleanWord.toUpperCase().trim();

  if (answer === 'СЛИТНО') {
    // 1. Derivative prepositions (слитно)
    if (['ВВИДУ', 'ВСЛЕДСТВИЕ', 'НАПОДОБИЕ', 'ВРОДЕ', 'ВМЕСТО', 'НАВСТРЕЧУ', 'НАСЧЁТ', 'НАСЧЕТ', 'СВЕРХ', 'ВСЛЕД', 'НАРЯДУ'].includes(w)) {
      return `«${w}» — производный предлог, пишется слитно; поэтому пишется СЛИТНО — «${w}».`;
    }
    // 2. Conjunctions & pronominal adverbs
    if (['ЧТОБЫ', 'ТАКЖЕ', 'ТОЖЕ', 'ЗАТО', 'ПРИТОМ', 'ПРИЧЁМ', 'ПРИЧЕМ', 'ПОЭТОМУ', 'ПОТОМУ', 'ПОЧЕМУ', 'ОТТОГО', 'ОТЧЕГО', 'ПОСКОЛЬКУ', 'ИТАК'].includes(w)) {
      if (['ПОЭТОМУ', 'ПОТОМУ', 'ПОЧЕМУ', 'ОТТОГО', 'ОТЧЕГО'].includes(w)) {
        return `«${w}» — местоименное наречие причины/следствия, пишется слитно; поэтому пишется СЛИТНО — «${w}».`;
      }
      if (['ПРИТОМ', 'ПРИЧЁМ', 'ПРИЧЕМ'].includes(w)) {
        return `«${w}» — присоединительный союз (= «к тому же»), пишется слитно; поэтому пишется СЛИТНО — «${w}».`;
      }
      if (['ИТАК'].includes(w)) {
        return `«${w}» — вводное слово со значением «таким образом», пишется слитно; поэтому пишется СЛИТНО — «${w}».`;
      }
      return `«${w}» — союз, пишется слитно; поэтому пишется СЛИТНО — «${w}».`;
    }
    // 3. Adverbs (слитно)
    return `«${w}» — наречие, пишется слитно; поэтому пишется СЛИТНО — «${w}».`;
  }

  if (answer === 'РАЗДЕЛЬНО') {
    // 1. Derivative prepositions & prepositional phrases (раздельно)
    if ([
      'В ТЕЧЕНИЕ', 'В ТЕЧЕНИИ', 'В ПРОДОЛЖЕНИЕ', 'В ПРОДОЛЖЕНИИ', 'В ЗАКЛЮЧЕНИЕ', 'В ЗАКЛЮЧЕНИИ',
      'В ВИДЕ', 'В СВЯЗИ', 'В СВЯЗИ С', 'НА ПРОТЯЖЕНИИ', 'ВО ИЗБЕЖАНИЕ', 'В СИЛУ', 'В ОТЛИЧИЕ',
      'В ОТЛИЧИЕ ОТ', 'ЗА СЧЁТ', 'ЗА СЧЕТ', 'ПО ПРИЧИНЕ', 'В ХОДЕ', 'В ПРОЦЕССЕ', 'ПО МЕРЕ',
      'В ВЕДЕНИИ', 'В КАЧЕСТВЕ'
    ].includes(w)) {
      return `«${w}» — производный предлог (предложное сочетание), пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }

    // 2. Conjunctions
    if (w === 'ТАК КАК') {
      return `«${w}» — составной союз причины, пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }
    if (w === 'КАК БУДТО') {
      return `«${w}» — сравнительный союз, всегда пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }
    if (w === 'ТО ЕСТЬ') {
      return `«${w}» — пояснительный союз, всегда пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }

    // 3. Words with particles ЖЕ, БЫ, ЛИ
    if (['ВСЁ ЖЕ', 'ВСЕ ЖЕ', 'ТЕПЕРЬ ЖЕ', 'ТОМУ ЖЕ', 'ТОЙ ЖЕ', 'ТЕ ЖЕ', 'ТУТ ЖЕ', 'ТУ ЖЕ', 'ТОТ ЖЕ'].includes(w)) {
      return `«${w}» — слово с усилительной частицей «же», пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }
    if (['ЕСЛИ БЫ', 'ХОТЯ БЫ', 'КАК БЫ', 'СКОЛЬ БЫ'].includes(w)) {
      return `«${w}» — слово с сослагательной частицей «бы», пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }
    if (['ЕДВА ЛИ', 'ЧУТЬ ЛИ', 'ВРЯД ЛИ'].includes(w)) {
      return `«${w}» — слово с частицей «ли», пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }

    // 4. Pronouns with prepositions
    if ([
      'ОТ ЭТОГО', 'ПРИ ЭТОМ', 'НА ЧЁМ', 'НА ЧЕМ', 'В ТОМ', 'ЗА ТО', 'ПО ЭТОМУ', 'ПО ТОМУ',
      'ОТ ТОГО', 'В ТО', 'К ТОМУ', 'О ТОМ'
    ].includes(w)) {
      return `«${w}» — местоимение с предлогом, пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }

    // 5. Reciprocal pronouns
    if (['ДРУГ ДРУГУ', 'ДРУГ ДРУГА', 'ДРУГ С ДРУГОМ', 'ВО ЧТО БЫ ТО НИ СТАЛО'].includes(w)) {
      return `«${w}» — устойчивое местоименное сочетание, пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }

    // 6. Modal phrases
    if (w === 'МОЖЕТ БЫТЬ') {
      return `«${w}» — вводное сочетание, пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }

    // 7. Set expressions
    if (['В КОНЦЕ КОНЦОВ', 'В ТО ЖЕ ВРЕМЯ', 'БОК О БОК', 'РУКА ОБ РУКУ', 'КАК РАЗ', 'ВСЁ РАВНО', 'ВСЕ РАВНО'].includes(w)) {
      return `«${w}» — устойчивое сочетание, пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
    }

    // 8. Prepositional nouns & adverbial combinations
    return `«${w}» — наречное сочетание существительного с предлогом, пишется раздельно; поэтому пишется РАЗДЕЛЬНО — «${w}».`;
  }

  return `«${w}» — пишется ${answer.toLowerCase()}; поэтому пишется ${answer} — «${w}».`;
}

